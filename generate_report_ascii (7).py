# generate_report_ascii.py – Simple PDF report for Assignment 3 (no pandas)
"""Creates a minimal ASCII PDF summarising the placeholder results for Assignment 3.
All metrics are read from the CSV files generated by each task script using the
standard library."""

import os
import csv
from fpdf import FPDF


def load_csv(path):
    if not os.path.exists(path):
        return None
    with open(path, newline="") as f:
        reader = csv.reader(f)
        rows = list(reader)
    if not rows:
        return None
    header = rows[0]
    data = rows[1:]
    return header, data


def main():
    base_dir = os.path.dirname(__file__)
    out_dir = os.path.join(base_dir, "outputs")
    os.makedirs(out_dir, exist_ok=True)
    pdf_path = os.path.join(out_dir, "Assignment3_Report.pdf")

    pdf = FPDF()
    pdf.add_page()
    pdf.set_font("Helvetica", "B", 16)
    pdf.cell(0, 10, "Smart Self-Checkout - Assignment 3 Report", ln=True, align="C")
    pdf.ln(8)
    pdf.set_font("Helvetica", size=12)
    tasks = [
        ("Task 1 - Processing Types", "task1_metrics.csv"),
        ("Task 2 - Preprocessing", "task2_metrics.csv"),
        ("Task 3 - Representation", "task3_metrics.csv"),
        ("Task 4 - Edge Detection", "task4_metrics.csv"),
        ("Task 5 - Corner Detection", "task5_metrics.csv"),
    ]
    for title, csv_name in tasks:
        pdf.set_font("Helvetica", "B", 12)
        pdf.cell(0, 8, title, ln=True)
        result = load_csv(os.path.join(out_dir, csv_name))
        pdf.set_font("Helvetica", size=11)
        if result:
            header, data = result
            pdf.cell(0, 6, f"Rows: {len(data)}", ln=True)
            cols = ", ".join(header[:3])
            pdf.cell(0, 6, f"Columns: {cols}", ln=True)
        else:
            pdf.set_font("Helvetica", "I", 11)
            pdf.cell(0, 6, "No data – task not executed.", ln=True)
        pdf.ln(4)
    pdf.output(pdf_path)
    print(f"Report written to {pdf_path}")

if __name__ == "__main__":
    main()
